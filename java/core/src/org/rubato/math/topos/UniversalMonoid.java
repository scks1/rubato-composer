package org.rubato.math.topos;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * The universal monoid Mon(C) of a finite category (arXiv 2611.32655,
 * Def. 2.1): the monoid generated by the arrows of C subject to
 * [g][f] = [g after f] for composable pairs, with every identity sent to
 * the unit.
 * <p>
 * An element is stored as its reduced word (Lemma 2.3): an array
 * u1 ... uk of non-identity arrows, index 0 holding u1, with
 * dom u(i) &ne; cod u(i+1) for every i. The word acts right to left, so
 * uk acts first. The empty array is the unit.
 */
public final class UniversalMonoid {

    /** The factorization m = w g of Lemma 2.4, with w in W_d and g : c -&gt; d. */
    public static final class Factorization {
        /** The word w in W_d. */
        public final int[] w;
        /** The arrow g : c -&gt; d of C, possibly an identity. */
        public final int g;

        Factorization(int[] w, int g) {
            this.w = w;
            this.g = g;
        }
    }

    private final FiniteCategory category;
    private final List<Integer> letters;

    public UniversalMonoid(FiniteCategory category) {
        this.category = category;
        List<Integer> l = new ArrayList<Integer>();
        for (int f = 0; f < category.arrowCount(); f++) {
            if (!isIdentity(f)) {
                l.add(f);
            }
        }
        letters = Collections.unmodifiableList(l);
    }

    public FiniteCategory category() {
        return category;
    }

    /** The generators: every non-identity arrow, in index order. */
    public List<Integer> letters() {
        return letters;
    }

    private boolean isIdentity(int f) {
        return category.identity(category.dom(f)) == f;
    }

    /**
     * The reduced word of the product [u1] ... [uk] (Lemma 2.3). A single
     * left-to-right pass suffices: each new letter u either stands right
     * of the last kept letter v, or replaces v by v after u when
     * dom v = cod u, and that composite drops out when it is an identity.
     * The composite has the codomain of v, so it never composes with the
     * letter before v, which was already reduced against v.
     */
    public int[] normalize(int... word) {
        int[] out = new int[word.length];
        int k = 0;
        for (int u : word) {
            if (isIdentity(u)) {
                continue;
            }
            if (k > 0 && category.dom(out[k - 1]) == category.cod(u)) {
                int vu = category.compose(out[k - 1], u);
                if (isIdentity(vu)) {
                    k--;
                } else {
                    out[k - 1] = vu;
                }
            } else {
                out[k++] = u;
            }
        }
        return Arrays.copyOf(out, k);
    }

    /** The product a b: b acts first. */
    public int[] multiply(int[] a, int[] b) {
        int[] ab = Arrays.copyOf(a, a.length + b.length);
        System.arraycopy(b, 0, ab, a.length, b.length);
        return normalize(ab);
    }

    /** True iff every letter is a non-identity arrow and no two neighbours compose (Lemma 2.3). */
    public boolean isReduced(int[] word) {
        for (int i = 0; i < word.length; i++) {
            if (isIdentity(word[i])) {
                return false;
            }
            if (i + 1 < word.length && category.dom(word[i]) == category.cod(word[i + 1])) {
                return false;
            }
        }
        return true;
    }

    /**
     * True iff the word lies in W_c (section 2.2): it is reduced and
     * either empty or its first-acting letter uk has dom uk &ne; c.
     */
    public boolean inW(int[] word, int c) {
        return isReduced(word) && (word.length == 0 || category.dom(word[word.length - 1]) != c);
    }

    /**
     * The unique factorization m = w g of Lemma 2.4 for an object c: g is
     * the identity of c when m lies in W_c, and otherwise the first-acting
     * letter of m, whose domain is c.
     *
     * @param m a word, normalized first
     */
    public Factorization factor(int[] m, int c) {
        int[] r = normalize(m);
        if (inW(r, c)) {
            return new Factorization(r, category.identity(c));
        }
        return new Factorization(Arrays.copyOf(r, r.length - 1), r[r.length - 1]);
    }

    /** Every reduced word of length at most maxLength, by length and then letter order. */
    public List<int[]> reducedWords(int maxLength) {
        List<int[]> out = new ArrayList<int[]>();
        List<int[]> level = new ArrayList<int[]>();
        level.add(new int[0]);
        out.add(new int[0]);
        for (int l = 1; l <= maxLength; l++) {
            List<int[]> next = new ArrayList<int[]>();
            for (int[] w : level) {
                for (int u : letters) {
                    if (w.length > 0 && category.dom(w[w.length - 1]) == category.cod(u)) {
                        continue;
                    }
                    int[] v = Arrays.copyOf(w, l);
                    v[l - 1] = u;
                    next.add(v);
                }
            }
            out.addAll(next);
            level = next;
        }
        return out;
    }

    /** The words of W_c of length at most maxLength. */
    public List<int[]> wordsW(int c, int maxLength) {
        List<int[]> out = new ArrayList<int[]>();
        for (int[] w : reducedWords(maxLength)) {
            if (inW(w, c)) {
                out.add(w);
            }
        }
        return out;
    }

    /**
     * True iff W_c is finite. A reduced word is a path in the graph on the
     * letters with an edge from u to v when v may stand right of u
     * (dom u &ne; cod v), so W_c is infinite exactly when a cycle can reach
     * a letter whose domain is not c.
     */
    public boolean isWFinite(int c) {
        int n = category.arrowCount();
        boolean[] reaches = new boolean[n];
        boolean changed = true;
        for (int u : letters) {
            reaches[u] = category.dom(u) != c;
        }
        while (changed) {
            changed = false;
            for (int u : letters) {
                if (reaches[u]) {
                    continue;
                }
                for (int v : letters) {
                    if (reaches[v] && category.dom(u) != category.cod(v)) {
                        reaches[u] = true;
                        changed = true;
                        break;
                    }
                }
            }
        }
        // a cycle among the letters that reach: peel off nodes with no successor among them
        boolean[] alive = reaches.clone();
        changed = true;
        while (changed) {
            changed = false;
            for (int u : letters) {
                if (!alive[u]) {
                    continue;
                }
                boolean hasNext = false;
                for (int v : letters) {
                    if (alive[v] && category.dom(u) != category.cod(v)) {
                        hasNext = true;
                        break;
                    }
                }
                if (!hasNext) {
                    alive[u] = false;
                    changed = true;
                }
            }
        }
        for (int u : letters) {
            if (alive[u]) {
                return false;
            }
        }
        return true;
    }

    /**
     * The word as arrow names separated by spaces, u1 first; "1" for the
     * unit. A name that itself holds a space is put in parentheses.
     */
    public String format(int[] word) {
        if (word.length == 0) {
            return "1";
        }
        StringBuilder b = new StringBuilder();
        for (int i = 0; i < word.length; i++) {
            if (i > 0) {
                b.append(' ');
            }
            String name = category.arrowName(word[i]);
            b.append(name.indexOf(' ') >= 0 ? "(" + name + ")" : name);
        }
        return b.toString();
    }
}
