package org.rubato.math.harmony;

import java.util.ArrayList;
import java.util.List;

import org.rubato.math.counterpoint.ZnAffine;

/**
 * Modulators and modulation quanta (Mazzola, <i>The Topos of Music I</i>,
 * &sect;27.1.4, Lemma 43, Def. 88 and Property 1, pp. 469&ndash;470;
 * Agust&iacute;n-Aquino and Mazzola, J. Math. Music 14, 2020, Defs. 3.1&ndash;3.2
 * and Algorithm 1, PDF p. 6).
 * <p>
 * For a modulation (g, &mu;) from S<sup>(k)</sup> to T<sup>(k)</sup>
 * properties (1), (2)<sub>&mu;</sub> and (4) leave one candidate: Q is the
 * orbit of the classes of &mu; under the group generated by g (Topos I,
 * p. 471, idea of proof of Thm. 30). The candidate is a quantum when T &cap; Q
 * is rigid, and, under {@link Filter#COVERED}, when the target chords inside
 * T &cap; Q cover it (property (3)). {@link Filter#ALGORITHM_1} drops the covering
 * half, as Algorithm 1 does, and records it in {@link Quantized#covered()}.
 * <p>
 * Rigidity is tested by default ({@link #DEFAULT_RIGIDITY}, Simon's choice
 * of 2026-11-23) under {@link Rigidity#AUT_X}: only the TI maps that send S
 * to one of its translates. This is a reconstruction of the counts of
 * Topos IV, App. P.1.1 (28 of 38 orbits agree, against 4 of 38 for TI12),
 * not a definition from the sources. {@link Rigidity#TI12} tests all 24 TI
 * maps, as property (3) and Algorithm 1's step 6 state. For the major scale
 * the two coincide, since every TI map sends it to a translate.
 */
public final class Modulations {

    /** Which half of property (3) is applied. */
    public enum Filter {
        /** Topos I Def. 88: rigid and covered by chords of the target. */
        COVERED,
        /** AM 2020 Algorithm 1: rigid only; uncovered rows are kept and flagged. */
        ALGORITHM_1
    }

    /** The group a trace must have no non-trivial symmetry in. */
    public enum Rigidity {
        /** All 24 maps x &#8614; &plusmn;x + t (property (3) as written). */
        TI12,
        /** Departure: only the TI maps sending S to a translate of S. */
        AUT_X
    }

    /** The reading the two-argument calls, the harmony rubettes and their defaults use. */
    public static final Rigidity DEFAULT_RIGIDITY = Rigidity.AUT_X;

    private static final List<ZnAffine> TI12 = new ArrayList<ZnAffine>();

    static {
        for (int v : new int[] { 1, -1 }) {
            for (int t = 0; t < PitchClasses.N; t++) {
                TI12.add(new ZnAffine(t, v, PitchClasses.N));
            }
        }
    }

    private Modulations() { /* static utility */ }

    /** The 24 maps x &#8614; x + t and x &#8614; t &minus; x, translations first. */
    public static List<ZnAffine> ti12() {
        return new ArrayList<ZnAffine>(TI12);
    }

    /** The TI maps that send the scale of s onto a translate of it. */
    public static List<ZnAffine> autX(Tonality s) {
        List<ZnAffine> out = new ArrayList<ZnAffine>();
        int sc = s.scaleMask();
        for (ZnAffine h : TI12) {
            int img = PitchClasses.apply(h, sc);
            for (int t = 0; t < PitchClasses.N; t++) {
                if (img == PitchClasses.transpose(sc, t)) {
                    out.add(h);
                    break;
                }
            }
        }
        return out;
    }

    /** True if no map of the group other than the identity fixes the set. */
    public static boolean isRigid(int set, List<ZnAffine> group) {
        for (ZnAffine h : group) {
            if (!(h.getTranslation() == 0 && h.getFactor() == 1) && PitchClasses.apply(h, set) == set) {
                return false;
            }
        }
        return true;
    }

    /** Lemma 43: the TI maps g with g(S) = T, translations first. */
    public static List<ZnAffine> modulators(Tonality s, Tonality t) {
        List<ZnAffine> out = new ArrayList<ZnAffine>();
        for (ZnAffine g : TI12) {
            if (PitchClasses.apply(g, s.scaleMask()) == t.scaleMask()) {
                out.add(g);
            }
        }
        return out;
    }

    /** The orbit of a set under the cyclic group generated by g. */
    public static int orbit(int set, ZnAffine g) {
        int q = set;
        int cur = set;
        for (int i = 0; i < 2 * PitchClasses.N; i++) {
            cur = PitchClasses.apply(g, cur);
            q |= cur;
        }
        return q;
    }

    /** All quantized modulations from s to t. */
    public static List<Quantized> quantize(Tonality s, Tonality t, Filter filter, Rigidity rigidity) {
        List<Quantized> out = new ArrayList<Quantized>();
        int p = Math.floorMod(t.tonic() - s.tonic(), PitchClasses.N);
        if (t.scaleMask() == s.scaleMask() || t.chordSize() != s.chordSize()) {
            return out;
        }
        List<ZnAffine> group = rigidity == Rigidity.TI12 ? TI12 : autX(s);
        List<Integer> cadences = Cadences.minimal(t);
        for (ZnAffine g : modulators(s, t)) {
            for (int mu : cadences) {
                int base = 0;
                for (int c : t.chordsOf(mu)) {
                    base |= c;
                }
                int q = orbit(base, g);
                int trace = q & t.scaleMask();
                if (!isRigid(trace, group)) {
                    continue;
                }
                int pivots = 0;
                int cover = 0;
                for (int d = 0; d < 7; d++) {
                    if (PitchClasses.isSubset(t.degree(d), trace)) {
                        pivots |= 1 << d;
                        cover |= t.degree(d);
                    }
                }
                boolean covered = cover == trace;
                if (filter == Filter.COVERED && !covered) {
                    continue;
                }
                out.add(new Quantized(p, mu, q, g, trace, pivots, covered));
            }
        }
        return out;
    }

    /** All quantized modulations from s to e<sup>p</sup>.s for p = 1 to 11. */
    public static List<Quantized> all(Tonality s, Filter filter, Rigidity rigidity) {
        List<Quantized> out = new ArrayList<Quantized>();
        for (int p = 1; p < PitchClasses.N; p++) {
            out.addAll(quantize(s, s.transpose(p), filter, rigidity));
        }
        return out;
    }

    /** "T3" for x &#8614; x + 3, "T9&#8728;&minus;1" for x &#8614; 9 &minus; x. */
    public static String name(ZnAffine g) {
        if (g == null) {
            return "?";
        }
        if (g.getFactor() == 1) {
            return "T" + g.getTranslation();
        }
        if (g.getFactor() == PitchClasses.N - 1) {
            return "T" + g.getTranslation() + "\u2218\u22121";
        }
        return g.toString();
    }
}
